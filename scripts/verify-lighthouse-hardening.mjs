import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
let failures = 0;
const pass = (m) => console.log(`PASS  ${m}`);
const fail = (m) => { failures += 1; console.log(`FAIL  ${m}`); };
const check = (c,m) => c ? pass(m) : fail(m);
const read = (f) => readFileSync(f,"utf8");
console.log("\nKathanika Media V52 — Lighthouse Hardening Verification\n");
const pkg=JSON.parse(read("package.json"));
check(pkg.name === "kathanika-media-v52-lighthouse-performance", "Package identifies V52 Lighthouse build");
check(pkg.version === "52.0.0", "Package version is 52.0.0");
const router=read("src/router.tsx"), root=read("src/routes/__root.tsx"), store=read("src/content/store.tsx"), hero=read("src/components/site/HeroOrbit.tsx");
check(!router.includes("@tanstack/react-query"), "Unused React Query runtime is removed from router");
check(!root.includes("QueryClientProvider"), "Unused QueryClientProvider is removed from root shell");
check(root.includes("kathanika-font-loader") && root.includes("window.addEventListener('load'"), "Google Fonts are deferred until after critical load");
check(store.includes('window.addEventListener("load", scheduleRefresh') && store.includes("1800"), "Apps Script content refresh is deferred until after critical render");
const image=read("src/components/site/ClientProductionImage.tsx");
check(image.includes('type="image/avif"'), "Production images prefer AVIF with WebP fallback");
check(image.includes("width={width}") && image.includes("height={height}"), "Responsive production images declare intrinsic dimensions");
check(image.includes("-1024.avif"), "High-DPR mobile has a 1024px AVIF candidate");
const d="public/media/production/responsive"; const avifs=readdirSync(d).filter(n=>n.endsWith(".avif"));
check(avifs.length >= 72, `At least 72 AVIF variants are packaged (${avifs.length})`);
const h=join(d,"IMG_4711-1024.avif");
check(existsSync(h) && statSync(h).size < 80000, `1024px LCP AVIF is under 80 KB (${existsSync(h)?Math.round(statSync(h).size/1024):0} KB)`);
check(root.includes("imageSrcSet") && root.includes("IMG_4711-1024.avif"), "Responsive AVIF hero preload is in the document head");
check(hero.includes("storyIndex === active"), "Inactive hero slides do not request media");
check(hero.includes("desktopSecondaryMedia") && hero.includes("(min-width: 641px)"), "Secondary hero imagery is deferred and omitted on mobile");
const css=read("src/styles.css");
check(css.includes('@source not "../src/components/ui";'), "Tailwind excludes unused UI component sources");
check(!css.includes('@import "tw-animate-css"'), "Unused animation stylesheet is removed");
const files=[]; const walk=(dir)=>{for(const e of readdirSync(dir,{withFileTypes:true})){const f=join(dir,e.name);if(e.isDirectory())walk(f);else if(e.name.endsWith(".tsx"))files.push(f)}}; walk("src");
const imgProblems=[], ariaProblems=[];
for(const f of files){const t=read(f);for(const m of t.matchAll(/<img\b[\s\S]*?>/g)){if(!/\bwidth=/.test(m[0])||!/\bheight=/.test(m[0]))imgProblems.push(f)}for(const m of t.matchAll(/<div\b[^>]*aria-label=[^>]*>/g)){if(!/\brole=/.test(m[0]))ariaProblems.push(f)}}
check(imgProblems.length===0, `All JSX images declare width and height${imgProblems.length?`: ${[...new Set(imgProblems)].join(", ")}`:""}`);
check(ariaProblems.length===0, `Generic labelled divs have semantic roles${ariaProblems.length?`: ${[...new Set(ariaProblems)].join(", ")}`:""}`);
check(read("public/CNAME").trim()==="www.kathanika.in", "Custom-domain CNAME remains intact");
if(failures){console.error(`\nLighthouse hardening verification failed with ${failures} issue(s).`);process.exit(1)}
console.log("\nLighthouse hardening verification passed.");
