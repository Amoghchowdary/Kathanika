import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const css = fs.readFileSync(path.join(root, "src/styles.css"), "utf8");
const hero = fs.readFileSync(path.join(root, "src/components/site/HeroOrbit.tsx"), "utf8");
const checks=[]; const failures=[];
const check=(ok,msg)=>{checks.push([!!ok,msg]); if(!ok) failures.push(msg)};
check(css.includes("flex: 0 0 100%;"), "Hero slide flex-basis is locked to one full viewport");
check(css.includes("max-width: 100%;"), "Hero slides have an explicit viewport maximum");
check(css.includes("max-width: 1120px;"), "Desktop hero copy measure is capped");
check(css.includes("font-size: clamp(58px, 5.35vw, 102px);"), "Desktop hero title has a 102px ceiling");
check(css.includes("font-size: clamp(50px, 9.2vw, 76px);"), "Tablet hero title has a 76px ceiling");
check(css.includes("font-size: clamp(42px, 13vw, 58px);"), "Mobile hero title has a 58px ceiling");
check(css.includes("overflow-wrap: normal;") && css.includes("hyphens: none;"), "Display words cannot split into letter fragments");
check(css.includes("@media (max-width: 1240px)"), "Desktop navigation switches before collision risk");
check(css.includes("@media (max-width: 900px)"), "Tablet layout breakpoint exists");
check(css.includes("@media (max-width: 640px)"), "Mobile layout breakpoint exists");
check(css.includes("@media (max-width: 420px)"), "Small-mobile breakpoint exists");
check(css.includes("@media (max-width: 360px)"), "320–360px safety breakpoint exists");
check(css.includes("height: 100dvh"), "Mobile overlay/modal uses dynamic viewport height");
check(css.includes("font-size: 16px; /* prevents iOS auto zoom */"), "Mobile forms prevent iOS focus zoom");
check(css.includes(".v41-work-covers") && css.includes("grid-template-columns: 1fr;"), "Work cards have a single-column mobile fallback");
check(css.includes(".v44-footer-grid") && css.includes("grid-template-columns: 1fr;"), "Footer has a single-column mobile fallback");
check(css.includes("overflow-x: clip"), "Horizontal page overflow is clipped globally");
check(hero.includes("translate3d(-${active * 100}%"), "Hero track advances exactly one viewport per story");
check(hero.includes("setInterval") && hero.includes("SLIDE_MS = 6200"), "Hero remains automatic at the intended cadence");
check(!hero.includes("onPointer") && !hero.includes("ArrowLeft") && !hero.includes("ArrowRight"), "Hero has no manual interaction that can disturb layout");
console.log("\nKathanika Media V46 — Responsive Geometry Verification\n");
for(const [ok,msg] of checks) console.log(`${ok?"PASS":"FAIL"}  ${msg}`);
if(failures.length){console.error(`\nResponsive verification failed: ${failures.length} issue(s).`);process.exit(1)}
console.log(`\nResponsive verification passed: ${checks.length} checks.`);
