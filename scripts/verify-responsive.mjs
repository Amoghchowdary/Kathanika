import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const css = fs.readFileSync(path.join(root, "src/styles.css"), "utf8");
const hero = fs.readFileSync(path.join(root, "src/components/site/HeroOrbit.tsx"), "utf8");
const checks=[]; const failures=[]; const check=(ok,msg)=>{checks.push([!!ok,msg]); if(!ok) failures.push(msg)};
check(css.includes("flex: 0 0 100%;"), "Hero slide flex-basis remains one full viewport");
check(css.includes("max-width: 100%;"), "Hero slides retain viewport containment");
check(css.includes("@media (max-width: 1100px)"), "Small-laptop/tablet bridge breakpoint exists");
check(css.includes("@media (max-width: 900px)"), "Tablet breakpoint exists");
check(css.includes("@media (max-width: 640px)"), "Mobile breakpoint exists");
check(css.includes("@media (max-width: 420px)"), "Small mobile breakpoint exists");
check(css.includes(".v41-page-head.v48-page-head") && css.includes("grid-template-columns: minmax(0, 1.35fr) minmax(300px, .65fr)"), "Desktop page head contains title and intro in safe fluid columns");
check(css.includes(".v50-production-wall") && css.includes("grid-template-columns: repeat(4, minmax(0, 1fr))"), "Production wall has fluid desktop grid");
check(css.includes(".v50-about-pillars") && css.includes("grid-template-columns: repeat(4, minmax(0, 1fr))"), "About icon cards have fluid desktop grid");
check(css.includes(".v49-footer-grid { grid-template-columns: 1fr; }"), "Footer has single-column tablet fallback");
check(css.includes("height: 100dvh"), "Mobile overlays use dynamic viewport height");
check(css.includes("overflow-x: clip"), "Global horizontal overflow protection remains enabled");
check(hero.includes("translate3d(-${active * 100}%"), "Hero advances exactly one viewport per story");
check(!hero.includes("onPointer") && !hero.includes("ArrowLeft") && !hero.includes("ArrowRight"), "Hero has no manual interactions that can disturb layout");
console.log("\nKathanika Media V51 — Responsive Geometry Verification\n");
for(const [ok,msg] of checks) console.log(`${ok?"PASS":"FAIL"}  ${msg}`);
if(failures.length){console.error(`\nResponsive verification failed: ${failures.length} issue(s).`);process.exit(1)}
console.log(`\nResponsive verification passed: ${checks.length} checks.`);
